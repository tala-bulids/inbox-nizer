from fastapi import APIRouter, HTTPException,Request
from schemas import EmailRequest
from predict import classify_email
from fastapi.responses import RedirectResponse, JSONResponse
from gmail_auth import create_google_flow


router = APIRouter()

@router.get("/auth/google")
def google_login():
    flow = create_google_flow()

    authorization_url, state = flow.authorization_url(
        access_type="offline",
        include_granted_scopes="true",
        prompt="consent"
    )

    response = RedirectResponse(authorization_url)

    response.set_cookie(
        key="oauth_state",
        value=state,
        httponly=True
    )

    # Keep the PKCE proof generated by this login for the callback Flow.
    response.set_cookie(
        key="oauth_code_verifier",
        value=flow.code_verifier,
        httponly=True,
        samesite="lax",
        max_age=600
    )

    return response

@router.get("/auth/google/callback")
def google_callback(
    code: str,
    state: str,
    request: Request
):
    saved_state = request.cookies.get("oauth_state")

    if state != saved_state:
        raise HTTPException(
            status_code=400,
            detail="Invalid OAuth state"
        )

    code_verifier = request.cookies.get("oauth_code_verifier")
    if not code_verifier:
        raise HTTPException(
            status_code=400,
            detail="OAuth session expired. Start Google login again."
        )

    flow = create_google_flow(state=state, code_verifier=code_verifier)

    flow.fetch_token(code=code)

    credentials = flow.credentials

    response = JSONResponse({
        "message": "Google account connected successfully"
    })
    response.delete_cookie("oauth_state")
    response.delete_cookie("oauth_code_verifier")
    return response

@router.post("/classify-email")
def classify(request: EmailRequest):
    try:
        result = classify_email(request.subject, request.body)

        return {
            "predictions": result
        }

    except Exception:
        raise HTTPException(
            status_code=500,
            detail="Email classification failed"
        )